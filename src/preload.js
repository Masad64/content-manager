  nichesAll: () => ipcRenderer.invoke('niches:all'),
  nichesSave: (list) => ipcRenderer.invoke('niches:save', list),
  settingsGet: () => ipcRenderer.invoke('settings:get'),
  settingsSet: (o) => ipcRenderer.invoke('settings:set', o),
  pickDataFolder: () => ipcRenderer.invoke('dialog:pickDataFolder'),
  pickVideosFolder: () => ipcRenderer.invoke('dialog:pickVideosFolder'),
  folderScan: (dir, niche, spread) => ipcRenderer.invoke('folder:scan', { dir, niche, spread }),
  driveStatus: () => ipcRenderer.invoke('drive:status'),
  driveSaveCreds: (id, secret) => ipcRenderer.invoke('drive:saveCreds', { id, secret }),
