  importFromFile: () => ipcRenderer.invoke('import:fromFile'),
  importAdd: (payload) => ipcRenderer.invoke('import:add', payload),
  openLink: (url) => ipcRenderer.invoke('shell:openExternal', url),
  openPath: (p) => ipcRenderer.invoke('shell:openPath', p),
  videoDownload: (id) => ipcRenderer.invoke('video:download', { id }),
  ytConnect: () => ipcRenderer.invoke('yt:connect'),
  ytStatus: () => ipcRenderer.invoke('yt:status'),
  ytDisconnect: () => ipcRenderer.invoke('yt:disconnect'),
  ytUpload: (id, visibility) => ipcRenderer.invoke('yt:upload', { id, visibility }),
  onYtStep: (cb) => ipcRenderer.on('yt:step', (_e, d) => cb(d)),
  onContentChanged: (cb) => ipcRenderer.on('content:changed', () => cb()),
  authCheck: (email, key) => ipcRenderer.invoke('auth:check', { email, key }),
  authStatus: () => ipcRenderer.invoke('auth:status'),
  usersList: () => ipcRenderer.invoke('users:list'),
  authLogout: () => ipcRenderer.invoke('auth:logout'),
  appVersion: () => ipcRenderer.invoke('app:version'),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateInstall: () => ipcRenderer.invoke('update:install'),
  onUpdateStatus: (cb) => ipcRenderer.on('update:status', (_e, d) => cb(d)),
  apiTest: (o) => ipcRenderer.invoke('api:test', o),
  mcpConfig: () => ipcRenderer.invoke('mcp:config'),
  dataReset: () => ipcRenderer.invoke('data:reset'),
  researchAll: () => ipcRenderer.invoke('research:all'),
  researchRun: () => ipcRenderer.invoke('research:run'),
  researchOne: (niche, query) => ipcRenderer.invoke('research:one', { niche, query }),
  ytQuota: () => ipcRenderer.invoke('yt:quota'),
  ytTestKey: () => ipcRenderer.invoke('yt:testKey'),
  nicheScan: (opts) => ipcRenderer.invoke('niche:scan', opts),
  nicheLastScan: () => ipcRenderer.invoke('niche:lastScan'),
  nicheClearScan: () => ipcRenderer.invoke('niche:clearScan'),
  nicheFindSimilar: (opts) => ipcRenderer.invoke('niche:findSimilar', opts),
  nicheSave: (item) => ipcRenderer.invoke('niche:save', item),
  nicheSaved: () => ipcRenderer.invoke('niche:saved'),
  nicheDaily: (force) => ipcRenderer.invoke('niche:daily', { force }),
  titleOptimize: (title, niche) => ipcRenderer.invoke('title:optimize', { title, niche }),
  titleAudit: (niche) => ipcRenderer.invoke('title:audit', { niche }),
  thumbOptimize: (image, niche, title) => ipcRenderer.invoke('thumb:optimize', { image, niche, title }),
  libAll: () => ipcRenderer.invoke('lib:all'),
  libAdd: (input) => ipcRenderer.invoke('lib:add', { input }),
  libRemove: (url) => ipcRenderer.invoke('lib:remove', { url }),
  libNote: (url, note) => ipcRenderer.invoke('lib:note', { url, note }),
  libRefresh: (url) => ipcRenderer.invoke('lib:refresh', { url }),
  libUpdate: (url, patch) => ipcRenderer.invoke('lib:update', { url, patch }),
  libDetail: (url) => ipcRenderer.invoke('lib:detail', { url }),
  uiZoom: (delta, reset) => ipcRenderer.invoke('ui:zoom', { delta, reset })
