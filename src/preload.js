  contentAll: () => ipcRenderer.invoke('content:all'),
  contentSave: (item) => ipcRenderer.invoke('content:save', item),
  contentDelete: (id) => ipcRenderer.invoke('content:delete', id),
  channelsAll: () => ipcRenderer.invoke('channels:all'),
