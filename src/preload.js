const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  contentAll: () => ipcRenderer.invoke('content:all'),
  contentSave: (item) => ipcRenderer.invoke('content:save', item),
  contentDelete: (id) => ipcRenderer.invoke('content:delete', id),
  channelsAll: () => ipcRenderer.invoke('channels:all'),
  channelsSave: (list) => ipcRenderer.invoke('channels:save', list),
  teamAll: () => ipcRenderer.invoke('team:all'),
  teamSave: (list) => ipcRenderer.invoke('team:save', list),
  nichesAll: () => ipcRenderer.invoke('niches:all'),
  nichesSave: (list) => ipcRenderer.invoke('niches:save', list),
  settingsGet: () => ipcRenderer.invoke('settings:get'),
  settingsSet: (o) => ipcRenderer.invoke('settings:set', o),
  pickDataFolder: () => ipcRenderer.invoke('dialog:pickDataFolder'),
  pickVideosFolder: () => ipcRenderer.invoke('dialog:pickVideosFolder'),
  driveStatus: () => ipcRenderer.invoke('drive:status'),
  driveSaveCreds: (id, secret) => ipcRenderer.invoke('drive:saveCreds', { id, secret }),
  driveConnect: () => ipcRenderer.invoke('drive:connect'),
  driveDisconnect: () => ipcRenderer.invoke('drive:disconnect'),
  driveUploadForContent: (contentId) => ipcRenderer.invoke('drive:uploadForContent', contentId),
  importFromUrl: (url) => ipcRenderer.invoke('import:fromUrl', url),
  importFromFile: () => ipcRenderer.invoke('import:fromFile'),
  importAdd: (payload) => ipcRenderer.invoke('import:add', payload),
  openLink: (url) => ipcRenderer.invoke('shell:openExternal', url),
  openPath: (p) => ipcRenderer.invoke('shell:openPath', p),
  videoDownload: (id) => ipcRenderer.invoke('video:download', { id }),
  ytConnect: () => ipcRenderer.invoke('yt:connect'),
  ytStatus: () => ipcRenderer.invoke('yt:status'),
  ytDisconnect: () => ipcRenderer.invoke('yt:disconnect'),
  ytUpload: (id, visibility) => ipcRenderer.invoke('yt:upload', { id, visibility }),
  onYtStep: (cb) => ipcRenderer.on('yt:step', (_e, d) => cb(d)),
  onContentChanged: (cb) => ipcRenderer.on('content:changed', () => cb()),
  authCheck: (email, key) => ipcRenderer.invoke('auth:check', { email, key }),
  authStatus: () => ipcRenderer.invoke('auth:status'),
  authLogout: () => ipcRenderer.invoke('auth:logout'),
  appVersion: () => ipcRenderer.invoke('app:version'),
  apiTest: (o) => ipcRenderer.invoke('api:test', o),
  mcpConfig: () => ipcRenderer.invoke('mcp:config'),
  dataReset: () => ipcRenderer.invoke('data:reset'),
  researchAll: () => ipcRenderer.invoke('research:all')
});
